// ---------------------------------------------------------------- 補助関数
const BPB = 4;
const PC = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
function mid(s) {
  const r = /^([A-G])([#b]?)(\d)$/.exec(s);
  if (!r) throw new Error('bad note ' + s);
  return 12 * (Number(r[3]) + 1) + PC[r[1]] + (r[2] === '#' ? 1 : r[2] === 'b' ? -1 : 0);
}
const NAMES = ['C', 'C#', 'D', 'Eb', 'E', 'F', 'F#', 'G', 'G#', 'A', 'Bb', 'B'];
const nameOf = (m) => NAMES[m % 12] + (Math.floor(m / 12) - 1);
// 決定的な小さな揺らぎ（整数ハッシュ）
function hash01(n) {
  let x = n | 0;
  x = Math.imul(x ^ (x >>> 16), 0x45d9f3b);
  x = Math.imul(x ^ (x >>> 16), 0x45d9f3b);
  x ^= x >>> 16;
  return (x >>> 0) / 4294967296;
}
const rnd = (x) => Math.round(x * 1000) / 1000;
const clampV = (v) => Math.max(0.05, Math.min(1, rnd(v)));

// 楽器ごとの既定値（ring = 書いた長さの後に弦を響かせておく拍数）
const DEF = {
  lyre: { ring: 0.35, pan: -0.1, contour: 0.004, center: 69 },
  bass: { ring: 0, pan: 0, contour: 0, center: 45 },
  strings: { ring: 0, pan: 0, contour: 0, center: 50 },
  flute: { ring: 0, pan: 0.25, contour: 0.003, center: 74 },
};

// 'beat:dur:Note[:vel] ...'（beat は小節の頭からの拍。4 以上なら次の小節へはみ出してよい）
function seq(out, inst, bar, src, o = {}) {
  const def = DEF[inst];
  const base = o.v ?? 0.5;
  const pan = o.pan ?? def.pan;
  const ring = o.ring ?? def.ring;
  const contour = o.contour ?? def.contour;
  const center = o.center ?? def.center;
  const tr = o.tr ?? 0;
  for (const tok of src.trim().split(/\s+/)) {
    const [b, d, n, vv] = tok.split(':');
    const beat = Number(b);
    const dur = Number(d);
    const m = mid(n) + tr;
    const t = bar * BPB + beat;
    let v;
    if (vv !== undefined && vv !== '') v = Number(vv) + (o.dv ?? 0);
    else {
      const accent = beat % 1 === 0 ? (beat % 2 === 0 ? 0.025 : 0.012) : 0;
      v = base + contour * (m - center) + accent + (hash01(Math.round(t * 48) * 7 + m * 131) - 0.5) * 0.035;
    }
    const dd = inst === 'flute' ? dur * 0.95 : dur + ring;
    out.push({ t: rnd(t), d: rnd(dd), m, i: inst, v: clampV(v), pan });
  }
}

// 弦の和音（最大3声）。声部ごとに左右へ少し広げる
function chord(out, bar, beat, dur, names, v) {
  const list = names.trim().split(/\s+/);
  const pans = list.length === 1 ? [0.15] : list.length === 2 ? [-0.22, 0.22] : [-0.25, 0.05, 0.28];
  list.forEach((n, k) => {
    const t = bar * BPB + beat;
    const jitter = (hash01(Math.round(t * 16) + k * 977) - 0.5) * 0.02;
    out.push({ t: rnd(t), d: rnd(dur), m: mid(n), i: 'strings', v: clampV(v + jitter - k * 0.01), pan: pans[k] });
  });
}

// 'dum@0:.55 tek@1.5:.3'
// B（12–27 小節）の縁打ち（tek・ka）だけ、決定的なごく小さなタイミングのずれ（±0.013 拍）を付けて機械的な硬さを和らげる。
// 中心打ちの dum は拍の格子に残す。
function drum(out, bar, src) {
  for (const tok of src.trim().split(/\s+/)) {
    const [k, rest] = tok.split('@');
    const [b, v] = rest.split(':');
    let t = bar * BPB + Number(b);
    if (bar >= 12 && bar <= 27 && (k === 'tek' || k === 'ka')) t += (hash01(Math.round(t * 64) * 31 + k.length * 7) - 0.5) * 0.026;
    const jitter = (hash01(Math.round(t * 32) * 13 + k.length * 101) - 0.5) * 0.03;
    out.push({ t: rnd(t), k, v: clampV(Number(v) + jitter) });
  }
}

// THEME をトークン列に（移調・区間指定つき）
function themeTokens(tr, from = 0, to = 16) {
  return THEME.filter((n) => n.t >= from && n.t < to)
    .map((n) => `${n.t - from}:${n.d}:${nameOf(n.m + tr)}`)
    .join(' ');
}

// 撥弦（竪琴・低音）で半音隣の弦が鳴ったら、前の音の響きをそこで止める。
// E5→F5、B4→C5 などの半音進行で余韻が重なって短2度にうなるのを防ぐ（奏者が手で弦を押さえる動作に相当）。
function dampSemitones(notes) {
  for (const inst of ['lyre', 'bass']) {
    const list = notes.filter((n) => n.i === inst);
    for (const n of list) {
      for (const q of list) {
        if (q === n || Math.abs(q.m - n.m) !== 1) continue;
        if (q.t >= n.t + 0.2 && q.t < n.t + n.d) n.d = rnd(Math.max(0.2, q.t - n.t + 0.05));
      }
    }
  }
}

